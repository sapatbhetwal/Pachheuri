/**
 * Format any numerical price in Nepalese Rupees format (e.g., "Rs. 2,500")
 */
export function formatNPR(amount) {
  const num = Number(amount) || 0
  return `Rs. ${num.toLocaleString('en-IN')}`
}

/**
 * Validate Nepal phone numbers:
 * Supports formats:
 * - 98XXXXXXXX / 97XXXXXXXX (10 digits)
 * - +977 98XXXXXXXX / +977-98XXXXXXXX
 * - +97798XXXXXXXX
 */
export function isValidNepalPhone(phone) {
  if (!phone) return false
  const clean = phone.replace(/[\s\-()]/g, '')
  return /^(\+977)?[9][78]\d{8}$/.test(clean) || /^0[1-9]\d{6,8}$/.test(clean)
}

/**
 * Format phone to standard +977 98XXXXXXXX
 */
export function formatNepalPhone(input) {
  if (!input) return ''
  let clean = input.replace(/[^\d+]/g, '')
  if (clean.startsWith('+977')) {
    const local = clean.slice(4)
    return `+977 ${local}`.trim()
  }
  if (clean.startsWith('977')) {
    const local = clean.slice(3)
    return `+977 ${local}`.trim()
  }
  return clean
}

